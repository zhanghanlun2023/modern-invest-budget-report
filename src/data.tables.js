MI.lineMap = {};
MI.TABLES.forEach(function (t) {
  t.map = {};
  t.lines.forEach(function (l) { t.map[l.c] = l; MI.lineMap[t.id + '.' + l.c] = l; });
  (t.lines2 || []).forEach(function (l) { t.map[l.c] = l; MI.lineMap[t.id + '.' + l.c] = l; });
});

MI.lineName = function (id, code) { var l = MI.lineMap[id + '.' + code]; return l ? l.n : code; };
MI.lineNo   = function (id, code) { var l = MI.lineMap[id + '.' + code]; return l && l.r ? String(l.r) : ''; };
MI.isEditableLine = function (id, code) {
  var l = MI.lineMap[id + '.' + code];
  return !!l && l.k !== 'grp' && !l.f;
};
MI.allLines = function (t) { return t.lines.concat(t.lines2 || []); };
